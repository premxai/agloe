"""Write the lab sections (P) of docs/RESULTS.md from data/lab/lab_results.json, between LAB markers (idempotent).

Usage: python -m scripts.write_results_lab
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from scripts.build_paper import NAMES

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "docs" / "RESULTS.md"
BEGIN, END = "<!-- LAB:BEGIN (generated by scripts/write_results_lab.py; do not edit by hand) -->", "<!-- LAB:END -->"


def pc(x, d=0):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def ci(d):
    return "n/a" if not d or d.get("rate") is None else f"{pc(d['rate'])} ({pc(d['lo'])}-{pc(d['hi'])})"


def n_(d):
    return f"{d.get('den', 0)} / {d.get('seeds', 0)} runs" if d else ""


def md(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


CLEAN_LABELS = {"everyone": "re-run everything", "after_tip": "re-check everything after the tip appeared", "earliest": "follow the earliest visible writer",
                "tags+backup": "follow the codes, earliest writer where a code was lost", "tags": "follow the codes only", "latest": "follow the latest visible writer"}


def cleanup_block() -> list[str]:
    """P.7: what an operator would re-check after a bad tip (from data/lab/cleanup_savings.json; see scripts/cleanup_savings.py)."""
    p = ROOT / "data" / "lab" / "cleanup_savings.json"
    if not p.exists():
        return []
    C = json.loads(p.read_text(encoding="utf-8"))
    out = ["### P.7 After a bad tip: what to re-check (`python -m scripts.cleanup_savings`)"]
    out.append("Planted-tip worlds with tags on. A re-check list is scored against the hidden read log: 'affected' = outputs whose chain of copying leads back to the planted post. "
               "'Wrong' outputs are those carrying the stale value (some reach it another way: agents that try the stale mirror on their own).\n")
    for scope, label in (("W2 tags", "Tip arrives mid-run (W2)"), ("W2E tags", "Tip is there from the start (W2E)")):
        a = C.get(scope)
        if not a:
            continue
        out.append(f"**{label}:** {a['runs']} runs, {a['outputs']:,} outputs; the tip reached {a['reached']:,}; {a['stale']:,} outputs were wrong ({a['stale_not_reached']:,} of them without any chain to the tip).\n")
        rows = []
        for k in ("everyone", "after_tip", "earliest", "tags+backup", "tags", "latest"):
            m = a["methods"][k]
            rows.append([CLEAN_LABELS[k], ci(m["flagged_share"]), ci(m["reached_found"]), ci(m["precision"]), ci(m["bad_found"])])
        out.append(md(["method", "share of outputs to re-check", "affected outputs found", "share of the list truly affected", "wrong outputs on the list"], rows))
        out.append("")
    out.append("Reading: tracing is what saves the work, not the tags as such. For a single-source tip the earliest-writer rule is nearly as good as the codes; the codes make the list "
               "exact (no false alarms) and matter when many posts carry the same link. When the tip is there from the start and the swarm adopts it, most outputs are affected and "
               "no list helps much: the saving comes from catching a tip early. A trace from the tip cannot find wrong outputs that arrive another way.\n")
    return out


def gated_block(L: dict, nm) -> list[str]:
    """P.8: the access-control experiment (W4 open vs W4G gated)."""
    G = {f: v for f, v in L.get("gated", {}).items() if v.get("W4") and v.get("W4G")}
    if not G:
        return []
    out = ["### P.8 Make the token the only way in (`python -m experiments.lab.run_lab --phase P8`)"]
    out.append("W4: a coordinator posts the team's working link, agents share their URLs on 'Notes', and the mirror root still hands out a session to anyone. W4G: the same, except the root hands out nothing, "
               "so every working request carries a link the wiki served. Load-bearing tokens in both. In W4G tracing follows from the access design: every output that exists holds a token the wiki served to that agent, and the token names the copy the agent was served "
               "(which can differ from the copy it fetched first when an agent reports a different link than the one it used, so attribution with tags is high but not 100%). "
               "So this experiment cannot discover an attribution accuracy; it measures what the gate costs and how much of the swarm ends up traceable.\n")
    rows = []
    for f, v in sorted(G.items(), key=lambda kv: kv[1]["W4"]["traceable"].get("rate") or 0):
        a, b = v["W4"], v["W4G"]
        rows.append([nm(f), f"{a['agents']} / {b['agents']}", f"{ci(a['completed'])} → {ci(b['completed'])}", f"{ci(a['traceable'])} → {ci(b['traceable'])}",
                     f"{ci(a['tag_survival'])} → {ci(b['tag_survival'])}", f"{ci(a['with_tags'])} → {ci(b['with_tags'])}", f"{a['failed_calls_per_agent']} → {b['failed_calls_per_agent']}"])
    out.append(md(["family", "agents (open / gated)", "agents that submitted the right answer", "outputs with a token naming their copy", "tag survival among copiers",
                   "source named correctly, with tags", "refused calls per agent"], rows))
    out.append("\nReading: gating lifts the traceable share for the models that otherwise re-derive access, and the price is calls spent on refused requests before the agent reads the wiki. "
               "What a gate cannot trace is an idea: an agent that learns which mirror works from a peer and then obtains access through another legitimate route leaves no token trail. "
               "Whether a real system can close every door the way this lab does is a deployment question this experiment does not answer.\n")
    return out


def build() -> str:
    L = json.loads((ROOT / "data" / "lab" / "lab_results.json").read_text(encoding="utf-8"))
    spend = json.loads((ROOT / "data" / "lab" / "spend.json").read_text(encoding="utf-8")) if (ROOT / "data" / "lab" / "spend.json").exists() else {}
    runs = sum(s.get("n", 0) for s in (json.loads(p.read_text(encoding="utf-8")) for p in (ROOT / "data" / "lab").glob("*/run.json"))
               if s.get("seed", 0) < 900)                     # same count as the paper and site: connectivity checks (seed >= 900) are not experiments
    nm = lambda f: NAMES.get(f, f)
    H1, H2, H3, H4 = L["H1"], L["H2"], L["H3"], L["H4"]
    out = [BEGIN, ""]
    out.append(f"## P. The lab (`experiments/lab`; `python -m experiments.lab.run_lab`, `python -m experiments.lab.analyze_lab`; Nebius open models only)")
    out.append(f"{L['cells']} cells, {runs:,} agent runs, ${spend.get('spent_usd', 0):.0f} spent in total (incl. pilots). Seed-pooled rates with a seed-level bootstrap 95% CI "
               "(min-max with fewer than 3 runs). All worlds offline (`.invalid`). Hidden read log = answer key; the copied item is the served copy the agent reproduced exactly (`prefer_exact`).")
    out.append(f"\n> {L['truth_note']}\n")
    out.append("**Stated in advance, and what happened.** H1 tags survive (load-bearing >= 90%, inert <= 10%); H2 tags beat the best simple edit-log rule by >= 10 points; "
               "H3 same-family 'random' values collide more than cross-family; H4 tags name the source of contaminated outputs for >= 80%; H5 (card ceiling vs measured) was "
               "dropped as stated: lab shared artifacts contain no distinctive strings without tags, so the card reports N/A there (section O).\n")

    out.append("### P.1 Model habits (H3: not supported as a within-family effect among open models)")
    ad = H3.get("adoption_rate", {})
    out.append(md(["family", "agents adding a cache-buster value", "most common value"],
                  [[nm(f), pc(v, 1), (f"`{H3['top_values'][f][0][0]}` x{H3['top_values'][f][0][1]}" if H3["top_values"].get(f) else "-")] for f, v in sorted(ad.items(), key=lambda kv: -kv[1]) if f != "gemma"]))
    out.append(f"\nWithin-family collision {H3.get('mean_within')} vs cross-family {H3.get('mean_cross')} (difference CI {H3.get('diff_ci95')}; families scored: {', '.join(nm(f) for f in H3.get('families_scored', []))}). "
               f"Naive-Bayes family classifier from behaviour: {pc(L['fingerprint_attribution'].get('accuracy'), 1)} vs chance {pc(L['fingerprint_attribution'].get('chance'), 1)} (leave-one-run-out; {L['fingerprint_attribution'].get('n_test')} agents).\n")

    out.append("### P.2 Tag survival per family (H1: holds only for verbatim copiers)")
    out.append(md(["family", "inert tag", "load-bearing token", "copiers (inert | load-bearing)"],
                  [[nm(f), ci(v["inert"]), ci(v["loadbearing"]), f"{v['inert'].get('den', 0)} | {v['loadbearing'].get('den', 0)}"] for f, v in H1["by_family"].items()
                   if v["inert"].get("den") or v["loadbearing"].get("den")]))
    out.append("\nMechanism (read from transcripts): Qwen copies the wiki link verbatim (list pages, read page, fetch the tokenized link, submit), so tags ride along; DeepSeek, Kimi and GLM "
               "read the wiki for the method and re-derive access (fetch the mirror root for their own session), so the wiki token is bypassed. Tags trace the artifact, not the idea. "
               "Design rule (untested here): make the token the only way in.\n")

    out.append("### P.3 Attribution: tags vs the best simple edit-log rule (H2: lift proportional to survival)")
    out.append(md(["family", "earliest", "latest", "best simple rule", "tag survival", "with tags (tag, else same rule)", "lift"],
                  [[nm(f), ci(v["edit_log_earliest"]), ci(v["edit_log_latest"]), ci(v["edit_log_only"]), ci(H1["by_family"][f]["loadbearing"]), ci(v["with_tags"]),
                    ("n/a" if v["lift_points"].get("rate") is None else f"{v['lift_points']['rate'] * 100:+.0f} pts")] for f, v in H2["by_family"].items() if v["with_tags"].get("den")]))
    out.append("\nBy world (all families pooled; dominated by the core model): "
               + "; ".join(f"{w}: best rule {ci(v['edit_log_only'])} vs tags {ci(v['with_tags'])} ({'n/a' if v['lift_points'].get('rate') is None else format(v['lift_points']['rate'] * 100, '+.0f') + ' pts'})"
                           for w, v in H2["by_world"].items() if v["with_tags"].get("den")) + ".\n")
    out.append("An earlier version let the tag tracer fall back to 'latest writer' while the baseline got the better rule; that made tags look harmful for four models (a flaw in the comparison). "
               "Fixed: the tag tracer falls back to the same best rule.\n")

    out.append("### P.4 A planted bad tip (W2 late, W2E early)")
    rows = []
    for key, v in H4.items():
        if not v.get("seeds"):
            continue
        w, c = key.split("|")
        ft = v["forward_trace"]
        tagged = c != "none"
        rows.append([w, c, v["seeds"], ci(v["spread_rate"]), ci(v["contaminated_attribution_with_tags"]) if tagged else "-", ci(v["contaminated_attribution_edit_log"]) if tagged else "-",
                     f"{ci(ft['tags']['precision'])} / {ci(ft['tags']['recall'])}" if tagged else "-",
                     f"{ci(ft['edit_log_earliest']['precision'])} / {ci(ft['edit_log_earliest']['recall'])}" if tagged else "-"])
    out.append(md(["world", "tags", "runs", "outputs with stale value", "source named: tags", "source named: best edit-log rule", "trace from origin via tags (P / R)", "via earliest writer (P / R)"], rows))
    out.append("\nFinding the origin of a single-source tip does not need tags (the earliest writer of that link is the origin). Tags give the exact chain. Late-tip adoption is bimodal run to run; "
               "tag-condition differences there are not attributed to tags.\n")
    out.append("By model: " + "; ".join(f"{nm(f)} late {ci(v)}" for f, v in L.get("rumor_by_family", {}).items() if v.get("rate") is not None and f != "gemma") + ".")
    if any(v.get("rate") is not None for v in L.get("early_rumor_by_family", {}).values()):
        out.append("Early tip: " + "; ".join(f"{nm(f)} {ci(v)}" for f, v in L["early_rumor_by_family"].items() if v.get("rate") is not None) + ".")
    out.append("")

    sw = L.get("size_sweep", {})
    if sw:
        out.append("### P.5 Swarm size, strong model, mixed swarm")
        out.append(md(["n agents", "tag survival", "with tags", "edit log (latest)", "copy share"],
                      [[n, ci(v["tag_survival"]), ci(v["with_tags"]), ci(v["edit_log_latest"]), ci(v["copy_share"])] for n, v in sw.items() if v["tag_survival"].get("rate") is not None]))
        sm = L.get("strong_model", {})
        out.append("\nStrong model (Qwen3.5-397B vs Qwen3-235B, W2): " + "; ".join(f"{nm(f)} {c}: stale {ci(v[c]['stale'])}, tag survival {ci(v[c]['tag_survival'])}" for f, v in sm.items() for c in ("none", "loadbearing")
                                                                               if v[c]["stale"].get("rate") is not None) + ".")
        mx = L.get("mixed_swarm", {})
        if any(v.get("seeds") for v in mx.values()):
            out.append("\nMixed swarm (8 families, W3): " + "; ".join(f"{c}: {v['seeds']} runs, cross-family copy share {ci(v['cross_family_copy_share'])}, tag survival {ci(v['tag_survival'])}" for c, v in mx.items() if v.get("seeds")) + ".")
        out.append("")
    out.append("### P.6 What went wrong in the lab (kept visible)")
    out.append("- Three flawed rumor designs set aside (`data/lab/_invalid_*`): the tip stated the value (agents submitted without fetching); the tip sat on a page nobody read (agents list pages and read one); "
               "the stale mirror warned about itself (agents self-corrected). Final design: notes protocol + mid-run tip + silent stale mirror, with an early-tip arm.")
    out.append("- A recency rule for the answer key mislabelled agents that re-read pages (DeepSeek lift looked like +2 points; with the exact served copy it is +21). Pooling worlds hid regimes.")
    out.append("- Gemma-3 never emitted tool calls and was dropped; gpt-oss and Nemotron rarely copy, so they contribute no tag results.")
    out.append("")
    out.extend(cleanup_block())
    out.extend(gated_block(L, nm))
    out.append(END)
    return "\n".join(out)


def main() -> None:
    text = RESULTS.read_text(encoding="utf-8")
    block = build()
    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    RESULTS.write_text(text, encoding="utf-8")
    print(f"-> {RESULTS} (lab block {len(block.splitlines())} lines)")


if __name__ == "__main__":
    main()
